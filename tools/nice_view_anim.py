#!/usr/bin/env python3
"""Turn an exported animation (C file from the spin editor) into nice!view frames.

Usage:
    python3 tools/nice_view_anim.py path/to/sharingan_anim.c

Input: a C file with `<name>_frames[N][FRAME_BYTES]` (68 x 140 px portrait,
1 bit per pixel, row-major, MSB = leftmost pixel, bit 1 = white) and
`<name>_frame_ms[N]` (how long each frame stays up).

Output: nice_view/widgets/anim_frames.c, drawn by nice_view/widgets/anim.c over
the top 136 px of the screen, leaving the bottom 24 px for the layer name.

What it does to fit the firmware:
- crops the 140 px portrait frames to 136 rows (the frames are blank at the
  top and bottom, and the layer name needs the last 24 px of the 160),
- rotates them 90 degrees, since the nice!view is mounted sideways and LVGL
  draws on a 160 x 68 landscape screen,
- stores frame 0 in full and every later frame only as the bytes that changed
  from the frame before (skip / copy runs), which takes 356 frames from about
  440 KB to about 85 KB.
"""

import re
import sys
from pathlib import Path

SRC_W, SRC_H = 68, 140
SRC_STRIDE = (SRC_W + 7) // 8
OUT_W, OUT_H = 136, 68  # landscape, as LVGL sees it
OUT_STRIDE = (OUT_W + 7) // 8
CROP_TOP = 2  # source rows 2..137 are kept

OUT = Path(__file__).resolve().parent.parent / "nice_view" / "widgets" / "anim_frames.c"


def parse(path):
    src = Path(path).read_text()
    m = re.search(r"(\w+)_frames\s*\[[^\]]*\]\s*\[[^\]]*\]\s*=\s*\{", src)
    if not m:
        sys.exit("No <name>_frames[N][BYTES] = { ... } array found.")
    name = m.group(1)
    body = src[m.end():src.index("};", m.end())]
    vals = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", body)]
    fb = SRC_STRIDE * SRC_H
    if len(vals) % fb:
        sys.exit(f"Frame data is {len(vals)} bytes, not a multiple of {fb} (68 x 140 px).")
    frames = [vals[i * fb:(i + 1) * fb] for i in range(len(vals) // fb)]
    m = re.search(rf"{name}_frame_ms\s*\[[^\]]*\]\s*=\s*\{{([^}}]*)\}}", src)
    if not m:
        sys.exit(f"No {name}_frame_ms[] array found.")
    ms = [int(x) for x in re.findall(r"\d+", m.group(1))]
    if len(ms) != len(frames):
        sys.exit(f"{len(frames)} frames but {len(ms)} durations.")
    return frames, ms


def rotate(frame):
    """Portrait (px, py) shows at landscape (x = 135 - py, y = px)."""
    out = bytearray(OUT_STRIDE * OUT_H)
    for y in range(OUT_H):
        for x in range(OUT_W):
            py = OUT_W - 1 - x + CROP_TOP
            if (frame[py * SRC_STRIDE + y // 8] >> (7 - y % 8)) & 1:
                out[y * OUT_STRIDE + x // 8] |= 0x80 >> (x % 8)
    return bytes(out)


def encode_delta(prev, cur):
    """Runs of (skip unchanged bytes, count, XOR bytes) until the frame ends."""
    d = bytes(a ^ b for a, b in zip(prev, cur))
    out = bytearray()
    i, n = 0, len(d)
    while i < n:
        skip = 0
        while i < n and d[i] == 0 and skip < 255:
            i += 1
            skip += 1
        j = i
        while j < n and d[j] != 0 and j - i < 255:
            j += 1
        out += bytes([skip, j - i]) + d[i:j]
        i = j
    return bytes(out)


def c_bytes(data, indent="    "):
    lines = []
    for i in range(0, len(data), 16):
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    frames, ms = parse(sys.argv[1])
    for f in frames:
        for py in list(range(CROP_TOP)) + list(range(CROP_TOP + OUT_W, SRC_H)):
            if any(f[py * SRC_STRIDE:(py + 1) * SRC_STRIDE]):
                print(f"warning: row {py} is not blank and gets cropped", file=sys.stderr)
                break
    rot = [rotate(f) for f in frames]
    deltas, offsets = bytearray(), []
    for k in range(len(rot)):
        offsets.append(len(deltas))
        deltas += encode_delta(rot[k - 1], rot[k])  # frame 0 is relative to the last
    offsets.append(len(deltas))

    OUT.write_text(f"""/* Generated by tools/nice_view_anim.py from {Path(sys.argv[1]).name}. Do not edit.
 * {len(rot)} frames, {OUT_W} x {OUT_H} px (landscape), 1 bit per pixel, bit 1 = white,
 * {sum(ms)} ms per loop. Frame 0 is stored whole; every frame k is then the XOR
 * against frame k-1 (frame 0 against the last frame) as runs of
 * [skip unchanged bytes][count][count bytes to XOR in].
 */

#include "anim_frames.h"

const uint16_t anim_frame_count = {len(rot)};

const uint8_t anim_first_frame[ANIM_FRAME_BYTES] = {{
{c_bytes(rot[0])}
}};

const uint8_t anim_deltas[] = {{
{c_bytes(deltas)}
}};

const uint32_t anim_delta_offsets[] = {{
{c_bytes_u32(offsets)}
}};

const uint16_t anim_frame_ms[] = {{
{c_ints(ms)}
}};
""")
    print(f"{OUT}: {len(rot)} frames, {len(deltas) + len(rot[0])} bytes of image data, "
          f"{sum(ms) / 1000:.1f} s per loop")


def c_bytes_u32(vals):
    return "\n".join("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ","
                     for i in range(0, len(vals), 12))


def c_ints(vals):
    return "\n".join("    " + ", ".join(str(v) for v in vals[i:i + 20]) + ","
                     for i in range(0, len(vals), 20))


if __name__ == "__main__":
    main()
